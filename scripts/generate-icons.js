// Writes src/icons.ts, which re-exports every icon in @iconify-icons/ri as
// `Ri<PascalCaseName>`. Run `npm run generate-icons` after bumping
// @iconify-icons/ri.
import { readFileSync, writeFileSync } from 'node:fs';

const pkg = JSON.parse(
  readFileSync(
    new URL('../node_modules/@iconify-icons/ri/package.json', import.meta.url),
    'utf8',
  ),
);

const lines = Object.keys(pkg.exports)
  .filter((key) => key !== '.' && key !== './package.json')
  .map((key) => {
    const name = key.slice(2);
    const exportName =
      'Ri' +
      name
        .split('-')
        .map((part) => part[0].toUpperCase() + part.slice(1))
        .join('');
    return `export { default as ${exportName} } from '@iconify-icons/ri/${name}';`;
  });

writeFileSync(
  new URL('../src/icons.ts', import.meta.url),
  `// Generated by scripts/generate-icons.js from @iconify-icons/ri@${pkg.version}. Do not edit.\n${lines.join('\n')}\n`,
);
